/*水仙花数
题目描述：打印所有的水仙花数。所谓水仙
花数是指一个三位数，其各位数字的立方和
等于该数。例如，153就是一个水仙花数，
因为153=1*1*1+5*5*5+3*3*3 */
#include <stdio.h>
int main (void)
{
	int a,b,c,i;
	for(i=100;i<=999;i++)
	{
		a = i % 10;
		b = i / 10 % 10;
		c = i / 100;
		if((a*a*a)+(b*b*b)+(c*c*c)==i)
		{
			printf("%d\n",i) ; 
		}
		
	}
	return 0;
}
